using System;
using BepInEx;
using BepInEx.Logging;
using ScamWYF.Modding.Core;
using ScamWYF.Modding.Core.Ui;
using UnityEngine.UIElements;

namespace ScamWYF.BetterBrowse
{
    /// <summary>
    /// Replaces the in-game browser's hardcoded Google search engine with Brave, DuckDuckGo,
    /// Ecosia, Bing, Startpage, a SearXNG instance, or any engine with a URL template.
    /// </summary>
    /// <remarks>
    /// The game funnels every address-bar navigation through KolkataOsBrowserHost.NormalizeBrowserUrl.
    /// Plain text becomes https://www.google.com/search?q=..., and the home page is read from
    /// 120-browser.json, which is also Google. One postfix on that method covers every search, and a
    /// small postfix/prefix pair moves the home page and the toolbar's magnifier button.
    ///
    /// Nothing about the embedded browser is replaced or reimplemented: the game still owns CEF,
    /// history, favicons, shortcuts and the address bar. The mod only rewrites the URL it is about to
    /// load.
    /// </remarks>
    // PluginBuildInfo.Version is generated by build.ps1 from this repository's git tag. It must stay
    // parseable by System.Version (two to four dot-separated integers); the commit lives in
    // PluginBuildInfo.Informational. See mod-lib's Version.ps1.
    [BepInPlugin(PluginGuid, "Scam WYF Better Browse", PluginBuildInfo.Version)]
    public sealed class Plugin : ScamMod
    {
        public const string PluginGuid = "com.community.scamwyf.betterbrowse";

        /// <summary>Unity build this mod was written against. A mismatch is a warning, not an error.</summary>
        private const string BuiltAgainst = "6000.3.26f1";

        internal static ManualLogSource Log;
        internal static Config Cfg;

        private static int _rewrites;
        private static string _lastQuery;
        private static string _lastUrl;
        private static int _hookCheck;

        /// <summary>Set while the startup hook check calls the patched method, so it is not counted.</summary>
        internal static bool Verifying;

        /// <summary>The plan the Harmony patches read. Rebuilt on every config reload.</summary>
        internal static SearchEnginePlan Plan
        {
            get
            {
                var cfg = Cfg;
                return cfg != null ? cfg.Plan : null;
            }
        }

        protected override void OnModLoad()
        {
            Log = ModLog;
            GameBuild.CheckUnityVersion(ModLog, ModId, BuiltAgainst);

            Cfg = new Config(Settings);
            WatchConfig();

            ModMenu.AddPage(this, "Search Engine", BuildPage, -15);

            Type hostType;
            var installed = BrowserPatches.Install(this, ModLog, out hostType);
            if (hostType != null && Cfg.Plan.Enabled)
            {
                _hookCheck = BrowserPatches.Verify(hostType, ModLog) ? 1 : 2;
            }

            if (!installed)
            {
                ModLog.LogWarning("No browser hooks were installed; the game is using Google exactly as " +
                                  "it ships. The menu tab still shows the settings and will say so.");
            }

            Cfg.Describe(ModLog);
        }

        protected override void OnConfigReloaded()
        {
            if (Cfg == null) return;

            // The patches only ever read a plan, so re-deriving it is the whole reload. No patch has
            // to be removed or reinstalled when the engine or the home page changes.
            Cfg.Rebuild();
            Cfg.Describe(ModLog);
            ModMenu.Refresh();
        }

        internal static void RecordRewrite(string query, string url)
        {
            if (Verifying) return;

            _rewrites++;
            _lastQuery = query;
            _lastUrl = url;

            var plan = Plan;
            if (plan != null && plan.Debug && Log != null)
            {
                Log.LogInfo("Search '" + query + "' -> " + url);
            }
        }

        // ---------------------------------------------------------------- the menu tab

        private void BuildPage(VisualElement page)
        {
            var plan = Cfg.Plan;

            Widgets.Heading(page, "Search engine");

            if (!plan.Enabled)
            {
                Widgets.Note(page, "Disabled. The browser is using Google exactly as the game ships it.",
                    true, false);
            }
            else
            {
                Widgets.FieldRow(page, "Provider", plan.ProviderName);
                Widgets.FieldRow(page, "Searches go to", plan.SearchTemplate);
                Widgets.FieldRow(page, "Home page",
                    plan.ReplacesHome ? plan.HomeUrl : "the game's own (Google)");
            }

            if (!string.IsNullOrEmpty(plan.Warning)) Widgets.Warning(page, plan.Warning);

            Widgets.Spacer(page, 8f);
            Widgets.Heading(page, "This session");

            Widgets.FieldRow(page, "Searches redirected", _rewrites.ToString());
            if (!string.IsNullOrEmpty(_lastQuery)) Widgets.FieldRow(page, "Last search", _lastQuery);
            if (!string.IsNullOrEmpty(_lastUrl)) Widgets.FieldRow(page, "Last URL", _lastUrl);

            var patches = PatchCoordinator.ForOwner(ModId);
            Widgets.FieldRow(page, "Hooks installed", patches.Length.ToString());
            Widgets.FieldRow(page, "Hook check", HookCheckText());
            foreach (var patch in patches)
            {
                Widgets.FieldRow(page, patch.Method, patch.Kinds);
            }

            if (patches.Length == 0)
            {
                Widgets.Warning(page, "No hooks are installed in this build, so nothing is being " +
                                      "redirected. See BepInEx/LogOutput.log for the method the mod " +
                                      "expected.");
            }

            Widgets.Spacer(page, 6f);

            var row = Widgets.WrapRow(page);
            Widgets.DescribedButton(row, "Re-read config",
                "Reload the file now, without restarting the game",
                delegate { ReloadConfig(); });

            Widgets.DescribedButton(row, "Reset counters",
                "Zero the search count shown above",
                delegate
                {
                    _rewrites = 0;
                    _lastQuery = null;
                    _lastUrl = null;
                    ModMenu.Refresh();
                });

            Widgets.Spacer(page, 8f);

            // The generated form comes last and starts closed: the live values above are what someone
            // opening this tab is looking for, and the descriptions are already in the .cfg.
            var fold = Widgets.Section(page, "All settings", false);
            var body = Widgets.SectionBody(fold);
            if (body == null)
            {
                ConfigEditor.Build(page);
                return;
            }

            Widgets.Paragraph(body,
                "Editing here writes straight to " + Config.ConfigFilePath +
                ". Editing that file while the game is running works too: it is watched, and the " +
                "change is picked up within about half a second.");

            ConfigEditor.Build(body);
        }

        private static string HookCheckText()
        {
            switch (_hookCheck)
            {
                case 1: return "passed";
                case 2: return "failed - see BepInEx/LogOutput.log";
                default: return "not run";
            }
        }
    }
}
